const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
  const p = await ctx.newPage();
  const errors = [];
  p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  p.on('pageerror', e => errors.push(String(e)));
  p.on('requestfailed', r => errors.push('FAILED ' + r.url()));
  await p.goto('http://localhost:5055/fa/menu', { waitUntil: 'networkidle' });
  await p.locator('[data-add-dish]').nth(0).click();
  await p.waitForTimeout(1200);
  await p.locator('[data-add-dish]').nth(0).click();
  await p.waitForTimeout(1200);
  await p.locator('[data-add-dish]').nth(2).click();
  await p.waitForTimeout(1200);
  console.log('badge', await p.locator('.site-header__cart-count').innerText());
  console.log('lines', await p.locator('.cart-line').count(), 'total', await p.locator('[data-cart-total]').innerText());
  await p.screenshot({ path: '/tmp/shots/cart-menu.png' });
  await p.locator('.cart-line__button').first().click(); // decrease first line? (less)
  await p.waitForTimeout(500);
  console.log('after less total', await p.locator('[data-cart-total]').innerText());
  await p.locator('[data-cart-checkout]').click();
  await p.waitForURL('**/checkout');
  await p.screenshot({ path: '/tmp/shots/checkout.png' });
  await p.locator('[data-fulfillment][value=delivery]').check({ force: true });
  await p.waitForTimeout(600);
  console.log('fee row hidden?', await p.locator('[data-quote-fee-row]').isHidden(), 'total', await p.locator('[data-quote-total]').innerText());
  await p.fill('#customer_name', 'علی رضایی');
  await p.fill('#customer_phone', '۰۹۱۲۳۴۵۶۷۸۹');
  await p.fill('#delivery_address', 'تهران، خیابان آزادی، پلاک ۱۲');
  await p.screenshot({ path: '/tmp/shots/checkout2.png' });
  await p.locator('.checkout__submit').click();
  await p.waitForURL('**/order/**');
  console.log('order url', p.url());
  await p.waitForTimeout(800);
  console.log('status', await p.locator('[data-status-label]').innerText());
  await p.screenshot({ path: '/tmp/shots/order1.png' });
  await p.locator('text=مرحله‌ی بعد').click();
  await p.waitForTimeout(2500);
  console.log('status after advance', await p.locator('[data-status-label]').innerText());
  await p.screenshot({ path: '/tmp/shots/order2.png' });
  console.log('badge after order', await p.locator('.site-header__cart-count').innerText());
  console.log('errors', JSON.stringify(errors));
  await b.close();
})();
